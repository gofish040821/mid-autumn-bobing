/* ---------------- 房间与人数 ---------------- */

/**
 * 默认房间 id。
 *
 * 现在每张桌都有自己的房间码，这个常量只用于两处：
 *   - 单测里直接 new GameEngine() 时给个确定值；
 *   - 不存在的房间一律按「找不到」处理，不做任何回退。
 */
export const ROOM_ID = 'MAIN_ROOM';
export const ROOM_TITLE = '月满中秋 · 今夜博饼局';

export const MIN_PLAYERS = 2;
export const MAX_PLAYERS = 15;

/**
 * 同时存在的房间数上限。
 *
 * 房间是纯内存对象，本身很便宜（一个房间才几 KB），这个上限不是为了省内存，
 * 而是挡住「脚本狂点创建房间」把进程撑爆——每次建房都会带一个定时器。
 * 真到了 200 桌同时开席的规模，该考虑的是换付费实例和多进程了。
 */
export const MAX_ROOMS = 200;

/**
 * 空房间（大厅里一个人都没有）闲置多久后被回收。
 *
 * 触发这个的条件很少：建房后没人来、或者最后一位客人掉线超过
 * LOBBY_GHOST_TTL_MS 被腾出席位。给足 2 分钟是因为「创建房间」
 * 到「朋友点进链接」之间本来就要等一会儿，不能刚建好就收走。
 */
export const EMPTY_ROOM_TTL_MS = 120_000;

/** 凑满（满员）后的自动开局倒计时。 */
export const AUTO_START_COUNTDOWN_MS = 5_000;

/**
 * 等待大厅里，玩家掉线多久之后被移出座位（好腾位置给别人）。
 * 游戏一旦开始就永不移除玩家，只标记 offline。
 * 刷新页面只需 1~2 秒即可重连，60 秒足够宽松。
 */
export const LOBBY_GHOST_TTL_MS = 60_000;

/**
 * 一桌人全部掉线多久之后，判定为「散场」，把这局作废、房间退回大厅。
 *
 * 没有这个兜底会出现死锁：牌局进行中所有人都关了页面（散场、断网、手机没电），
 * 房间会永远停在 NORMAL_TURN / FINISHED —— 真人进不来（提示「本桌已经开席」），
 * 而房主也不在线，没人能重开。只能重启服务进程。
 *
 * 给到 2 分钟是因为要区分两种情况：
 *   - 短暂掉线（切后台、Wi-Fi 抖动、手机息屏）：1~2 秒就重连回来了，不该毁掉牌局；
 *   - 真的散场：人都走了，牌局留着也没意义。
 * 注意这条只在「一个人都不在线」时才计时，只要还有一个人在，牌局一律继续。
 */
export const ABANDON_GRACE_MS = Number(process.env.ABANDON_GRACE_MS ?? 120_000);

/* ---------------- 回合 ---------------- */

/** 在线玩家的思考时间；超过由服务器自动代掷。 */
export const TURN_TIMEOUT_MS = 5_000;

/**
 * 已经**离线**的玩家轮到时，全桌只等这么久。
 *
 * 人都不在了，等满 5 秒只是让一桌人陪着一个空座位干等——代掷该发生还是会
 * 发生，区别只在于大家盯着倒计时多熬 2 秒。所以离线的座位给 3 秒就够：
 * 足够等到一个正在重连的人（刷新页面通常一两秒就回来了），又不至于拖住牌局。
 *
 * 注意这是「轮到他的那一次」的等待，不是把在线玩家的思考时间也砍短了——
 * 在线的人依然是 TURN_TIMEOUT_MS。
 */
export const TURN_TIMEOUT_OFFLINE_MS = 3_000;

/**
 * 开奖后到下一回合之间的「演出时间」。
 *
 * 具体时长由 shared/src/timing.ts 的 ROLL_TIMING 表决定
 * （骰子动画 + 中奖演出 + 缓冲），客户端读同一张表，
 * 所以两边的节奏永远一致。想整体调快/调慢就改那张表。
 */
export { ROLL_TIMING, TRANSITION_BUFFER_MS, transitionMsFor } from '@bobing/shared';

/* ---------------- 状元 ---------------- */

/**
 * 最终状元额外奖励。
 *
 * 状元是**彩头**，不是本局的排期事件：这局什么时候收席由饼定，不由状元定。
 *
 * 曾经这里还有过「月华加持」与「状元保底」两套参数，用来保证每局都
 * 博得出一个状元——它们是靠**直接构造一副状元骰子**实现的，也就是在
 * 随机数之外人为改点数。现在骰子完全随机（六颗均匀 1~6，见 DiceService），
 * 于是：每次掷骰出状元档的概率是 561/46656 ≈ 1.2024%，**约十分之一的牌局
 * 一个状元都没有**，状元饼原封留在桌上，这是正常结局。
 *
 * 「没有状元的局有多少」不只看这个概率，还看一局掷多少次：牌局越长，
 * 撞上状元的机会越多。上面那个十分之一是 63 份一桌（中位约 209 掷）的实测；
 * 早先 57 份一桌约 125 掷时，这个数是四分之一。
 *
 * 想让状元更常见，唯一正当的做法是改判奖表本身（shared/src/awards.ts），
 * 不要去碰骰子。
 */
export const CHAMPION_BONUS = 100;

/* ---------------- 历史与日志 ---------------- */

/**
 * 两个都是**滚动窗口**：写满之后从**头部**丢弃最老的，保留最近的。
 *
 * 它们存在的理由是**广播体积** —— 整个快照挂在每一次开奖广播上发给全桌，
 * 而一条掷骰记录就几百字节。不封顶的话，一局几百掷之后每次广播都要带上
 * 全部历史，白白拖垮长局。
 *
 * ⚠️ 换成 63 份一桌之后，这两个上限从「永远碰不到」变成了**常态触发**：
 * 一局中位 209 掷、p99 446 掷，所以 `MAX_ROLL_HISTORY`（300）在一半以上的
 * 局里都会溢出，早期掷骰会被丢掉。
 *
 * 这**不影响玩家看到的东西**：`gameLog` 是「今夜博饼纪事」那一栏，客户端
 * 按最新在前渲染（见 GameLog.tsx），滚动窗口丢掉的正好是滚出视野的那些；
 * 而 `rollHistory` 客户端根本没有读（只有冒烟脚本拿它对账）。
 *
 * 所以：**不要因为「想留下完整对局记录」就把这两个数调大**，那是在给每一次
 * 广播加负担。真要做完整复盘，应当另开一条不带在快照里的接口。
 */
export const MAX_LOG_ENTRIES = 200;
export const MAX_ROLL_HISTORY = 300;

